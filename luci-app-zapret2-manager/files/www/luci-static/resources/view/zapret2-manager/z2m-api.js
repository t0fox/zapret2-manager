function normalizeError(error) {
  if (error == null) return { code: 'unknown', message: _('Неизвестная ошибка') };
  if (typeof error === 'string') return { code: 'error', message: error };
  var value = error.error != null ? error.error : error;
  if (typeof value === 'string') return { code: error.code || 'error', message: value };
  return {
    code: value.code || error.code || 'error',
    message: value.message || error.message || value.detail || error.detail || _('Неизвестная ошибка'),
    details: value.details || error.details || null
  };
}

